import cv2
import numpy as np
image = cv2.imread(r"C:\picture\colour.jpg")
image = cv2.resize(image, (400, 400))
hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
lower_green = np.array([40,50,50])
upper_green = np.array([80,255,255])
green_mask = cv2.inRange(hsv, lower_green, upper_green)
green_result = cv2.bitwise_and(image, image, mask=green_mask)
green_mask_bgr = cv2.cvtColor(green_mask, cv2.COLOR_GRAY2BGR)
cv2.putText(image, "Original Image", (20,20),cv2.FONT_HERSHEY_SIMPLEX,1, (0,0,0), 2)
cv2.putText(green_mask_bgr, "Green Mask", (20,50),cv2.FONT_HERSHEY_SIMPLEX,1, (0,255,255), 2)
cv2.putText(green_result, "Green Detection", (20,50),cv2.FONT_HERSHEY_SIMPLEX,1, (0,255,255), 2)
image_green = cv2.copyMakeBorder(image,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
green_mask_bgr = cv2.copyMakeBorder(green_mask_bgr,10,10,10,10,cv2.BORDER_CONSTANT,value=(0,255,0))
green_result = cv2.copyMakeBorder(green_result,10,10,10,10,cv2.BORDER_CONSTANT,value=(0,255,0))
final_green = np.hstack((image_green, green_mask_bgr, green_result))
lower_blue = np.array([100,150,50])
upper_blue = np.array([140,255,255])
blue_mask = cv2.inRange(hsv, lower_blue, upper_blue)
blue_result = cv2.bitwise_and(image, image, mask=blue_mask)
blue_mask_bgr = cv2.cvtColor(blue_mask, cv2.COLOR_GRAY2BGR)
cv2.putText(blue_mask_bgr, "Blue Mask", (20,20), cv2.FONT_HERSHEY_SIMPLEX,1, (255,255,255), 2)
cv2.putText(blue_result, "Blue Detection", (20,20), cv2.FONT_HERSHEY_SIMPLEX,1, (255,255,255), 2)
image_blue = cv2.copyMakeBorder(image,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
blue_mask_bgr = cv2.copyMakeBorder(blue_mask_bgr,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
blue_result = cv2.copyMakeBorder(blue_result,10,10,10,10, cv2.BORDER_CONSTANT,value=(255,255,255))
final_blue = np.hstack((image_blue, blue_mask_bgr, blue_result))
lower_red1 = np.array([0,120,70])
upper_red1 = np.array([10,255,255])
lower_red2 = np.array([170,120,70])
upper_red2 = np.array([180,255,255])
mask1 = cv2.inRange(hsv, lower_red1, upper_red1)
mask2 = cv2.inRange(hsv, lower_red2, upper_red2)
red_mask = mask1 + mask2
red_result = cv2.bitwise_and(image, image, mask=red_mask)
red_mask_bgr = cv2.cvtColor(red_mask, cv2.COLOR_GRAY2BGR)
cv2.putText(red_mask_bgr, "Red Mask", (20,20),cv2.FONT_HERSHEY_SIMPLEX,1, (255,255,255), 2)
cv2.putText(red_result, "Red Detection", (20,20),cv2.FONT_HERSHEY_SIMPLEX,1, (255,255,255), 2)
image_red = cv2.copyMakeBorder(image,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
red_mask_bgr = cv2.copyMakeBorder(red_mask_bgr,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
red_result = cv2.copyMakeBorder(red_result,10,10,10,10,cv2.BORDER_CONSTANT,value=(255,255,255))
final_red = np.hstack((image_red, red_mask_bgr, red_result))
cv2.imshow("Red Detection Project", final_red)
cv2.imshow("Blue Detection Project", final_blue)
cv2.imshow("Green Detection Project", final_green)
cv2.waitKey(0)
cv2.destroyAllWindows() 